-- =========================================================
-- Tracker 프로젝트 스키마
-- 로컬 Oracle DB(SQL Developer)에서 확인한 실제 컬럼 정의(타입/길이/NOT NULL/기본값)를
-- 그대로 반영해서 작성했습니다. TASK_ID / CATEGORY_ID는 로컬 DB에서도
-- IDENTITY 컬럼(ISEQ$$_... 시퀀스)으로 되어 있어 동일하게 IDENTITY로 정의했습니다.
-- =========================================================

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = TRACKER;

CREATE TABLE USERS (
    USER_ID       VARCHAR2(30)  NOT NULL PRIMARY KEY,
    USER_PASSWORD VARCHAR2(100) NOT NULL,
    NAME          VARCHAR2(30)  NOT NULL,
    EMAIL         VARCHAR2(100) NOT NULL,
    ROLE          VARCHAR2(30)  DEFAULT 'USER'   NOT NULL,
    STATUS        VARCHAR2(30)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_DATE  DATE          DEFAULT SYSDATE  NOT NULL,
    UPDATED_DATE  DATE          DEFAULT SYSDATE  NOT NULL
);

CREATE TABLE TASK_CATEGORY (
    CATEGORY_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    TITLE         VARCHAR2(100) NOT NULL,
    DESCRIPTION   VARCHAR2(300),
    WORK_ROLE     VARCHAR2(50),
    USER_ID       VARCHAR2(30)  NOT NULL,
    STATUS        VARCHAR2(30)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_DATE  DATE          DEFAULT SYSDATE  NOT NULL,
    UPDATED_DATE  DATE          DEFAULT SYSDATE  NOT NULL,
    CONSTRAINT FK_CATEGORY_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

CREATE TABLE TASK (
    TASK_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    TASK_TITLE    VARCHAR2(100)  NOT NULL,
    TASK_CONTENT  VARCHAR2(1000),
    PRIORITY      VARCHAR2(20)   DEFAULT 'NORMAL' NOT NULL,
    DUE_DATE      DATE,
    USER_ID       VARCHAR2(30)   NOT NULL,
    CATEGORY_ID   NUMBER         NOT NULL,
    STATUS        VARCHAR2(30)   DEFAULT 'ACTIVE' NOT NULL,
    CREATED_DATE  DATE           DEFAULT SYSDATE  NOT NULL,
    UPDATED_DATE  DATE           DEFAULT SYSDATE  NOT NULL,
    TASK_STATUS   VARCHAR2(30)   DEFAULT 'TODO'   NOT NULL,
    CONSTRAINT FK_TASK_USER     FOREIGN KEY (USER_ID)     REFERENCES USERS(USER_ID),
    CONSTRAINT FK_TASK_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES TASK_CATEGORY(CATEGORY_ID)
);

CREATE SEQUENCE SEQ_TASK_LOG START WITH 1 INCREMENT BY 1;

CREATE TABLE TASK_LOG (
    LOG_ID         NUMBER        NOT NULL PRIMARY KEY,
    TASK_ID        NUMBER        NOT NULL,
    USER_ID        VARCHAR2(30)  NOT NULL,
    ACTION_TYPE    VARCHAR2(30)  NOT NULL,
    BEFORE_STATUS  VARCHAR2(30),
    AFTER_STATUS   VARCHAR2(30),
    CREATED_DATE   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_TASKLOG_TASK FOREIGN KEY (TASK_ID) REFERENCES TASK(TASK_ID)
);

CREATE INDEX IDX_TASK_USER_DUEDATE ON TASK(USER_ID, DUE_DATE);
CREATE INDEX IDX_TASKLOG_TASK_ID   ON TASK_LOG(TASK_ID);
